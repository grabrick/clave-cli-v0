"""ПРАВИЛО 2: «сошлось» не имеет права стоять в одиночку.

Гейты ловят механическую поломку (сборка, тесты, clippy, fmt), визуальную регрессию и провал
assertions. Верность решения задачи не ловит НИЧТО — и это не оговорка в документации, а свойство
критерия. Выдать «converged: true» и надеяться, что человек сам вспомнит про эту разницу, — то же
враньё, только вежливое.

Поэтому исход всегда едет вместе с перечнем того, что машина НЕ проверяла. Пусть неудобно.

Отдельно ловим самый дешёвый признак недоказанности: правка кода, к которой не добавлено ни
одного теста. Такую правку не проверяет ничто, кроме того, что она компилируется. Именно так в
этом проекте появился поллинг `git` каждые две секунды: все гейты были зелёные, тестов не было,
и не заметил никто — ни исполнитель, ни критик.
"""
from __future__ import annotations

import re

# Rust держит тесты в том же файле (`#[test]`), Python — в tests/ (`def test_`).
# Считаем по диффу, а не по путям: иначе Rust-правка с тестами выглядела бы как правка без них.
_TEST_ADDED = re.compile(r"^\+\s*(#\[test\]|(?:async )?def test_)", re.M)


def tests_added(diff_text: str) -> int:
    """Сколько тестов добавила правка."""
    return len(_TEST_ADDED.findall(diff_text or ""))


def unverified(changed, diff_text: str, converged: bool) -> list:
    """Чего машина НЕ проверила. Печатается ВСЕГДА, рядом с исходом."""
    lines = [
        "решена ли задача ВЕРНО — машина не проверяла и не умеет. Гейты говорят «не сломал», "
        "а не «сделал». Читай дифф.",
    ]

    added = tests_added(diff_text)
    files = len(changed or ())
    if files and not added:
        lines.append(
            f"изменено файлов: {files}, добавлено тестов: 0 — правку не проверяет ничто, "
            "кроме того, что она компилируется"
        )
    elif files:
        lines.append(f"изменено файлов: {files}, добавлено тестов: {added}")

    if not converged:
        lines.append("исход не «сошлось» — тем более читай дифф целиком, а не только отчёт")
    return lines
